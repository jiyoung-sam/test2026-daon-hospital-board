-- 다온한방병원 게시판 데이터베이스 설정
-- Supabase Dashboard > SQL Editor에서 전체 내용을 실행하세요.
-- 이 스크립트는 공개 키를 사용하는 브라우저 앱을 RLS 정책으로 보호합니다.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '회원',
  role text not null default 'member' check (role in ('member', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.profiles(id) on delete restrict,
  title text not null check (char_length(title) between 1 and 120),
  content text not null check (char_length(content) between 1 and 10000),
  is_notice boolean not null default false,
  image_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  author_id uuid not null references public.profiles(id) on delete restrict,
  content text not null check (char_length(content) between 1 and 1000),
  created_at timestamptz not null default now()
);

create index if not exists posts_created_at_idx on public.posts(created_at desc);
create index if not exists posts_notice_idx on public.posts(is_notice desc, created_at desc);
create index if not exists comments_post_id_idx on public.comments(post_id, created_at);

-- 신규 가입 시 profiles에 기본 회원 정보를 자동 생성합니다.
create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data->>'display_name', ''), split_part(new.email, '@', 1), '회원')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute procedure public.create_profile_for_new_user();

-- updated_at 자동 갱신
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
drop trigger if exists posts_set_updated_at on public.posts;
create trigger posts_set_updated_at before update on public.posts
for each row execute procedure public.set_updated_at();

-- 관리자 여부 확인 함수. 클라이언트가 role을 임의로 변경할 수 없도록 별도 함수로 검사합니다.
create or replace function public.is_board_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

alter table public.profiles enable row level security;
alter table public.posts enable row level security;
alter table public.comments enable row level security;

-- 프로필은 게시판 작성자 이름을 표시하기 위해 읽기 허용. 수정은 본인 이름만 가능.
drop policy if exists "profiles are readable" on public.profiles;
create policy "profiles are readable" on public.profiles
for select using (true);

drop policy if exists "users update own profile name" on public.profiles;
create policy "users update own profile name" on public.profiles
for update to authenticated
using (id = auth.uid())
with check (id = auth.uid() and role = 'member');

-- 게시글은 누구나 읽을 수 있습니다.
drop policy if exists "posts are readable" on public.posts;
create policy "posts are readable" on public.posts
for select using (true);

-- 로그인한 회원은 일반 게시글을 작성하고, 관리자는 공지사항도 작성할 수 있습니다.
drop policy if exists "members create posts" on public.posts;
create policy "members create posts" on public.posts
for insert to authenticated
with check (
  author_id = auth.uid()
  and (is_notice = false or public.is_board_admin())
);

-- 작성자 본인 또는 관리자가 수정할 수 있습니다. 일반 회원은 공지로 바꿀 수 없습니다.
drop policy if exists "authors and admins update posts" on public.posts;
create policy "authors and admins update posts" on public.posts
for update to authenticated
using (author_id = auth.uid() or public.is_board_admin())
with check (
  public.is_board_admin()
  or (author_id = auth.uid() and is_notice = false)
);

drop policy if exists "authors and admins delete posts" on public.posts;
create policy "authors and admins delete posts" on public.posts
for delete to authenticated
using (author_id = auth.uid() or public.is_board_admin());

drop policy if exists "comments are readable" on public.comments;
create policy "comments are readable" on public.comments
for select using (true);

drop policy if exists "members create own comments" on public.comments;
create policy "members create own comments" on public.comments
for insert to authenticated
with check (author_id = auth.uid());

drop policy if exists "authors and admins delete comments" on public.comments;
create policy "authors and admins delete comments" on public.comments
for delete to authenticated
using (author_id = auth.uid() or public.is_board_admin());

-- 이미지 저장소: 공개 읽기, 로그인 회원은 본인 UUID 폴더에 업로드 가능
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('post-images', 'post-images', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "post images are publicly readable" on storage.objects;
create policy "post images are publicly readable" on storage.objects
for select using (bucket_id = 'post-images');

drop policy if exists "members upload into own folder" on storage.objects;
create policy "members upload into own folder" on storage.objects
for insert to authenticated
with check (
  bucket_id = 'post-images'
  and (storage.foldername(name))[1] = auth.uid()::text
);

drop policy if exists "owners and admins delete post images" on storage.objects;
create policy "owners and admins delete post images" on storage.objects
for delete to authenticated
using (
  bucket_id = 'post-images'
  and (
    (storage.foldername(name))[1] = auth.uid()::text
    or public.is_board_admin()
  )
);

